#!/usr/bin/env node
/**
 * dev-channels.mjs — local-dev channel installer for a dsh profile.
 *
 * Links the @wsz987/dsh-channels bundle from this workspace into a DeepSeek
 * Harness profile, so the channels can be developed without publishing
 * anything to npm. The profile receives exactly the same single direct bundle
 * dependency as a registry install.
 *
 * Usage (from the repo root):
 *   node scripts/dev-channels.mjs [options] [channel...]
 *   pnpm channels [channel...]            # shorthand, see package.json
 *
 *   --profile <name>   target profile (default: web)
 *   --all              install every channel (default when no channel is given)
 *   -h, --help         this help
 *
 * Channels are short names derived from the bundle patch
 * (packages/channels/cordis.patch.yml): `channels-weixin` -> `weixin`, etc.
 * Available channels and aliases are printed by --help / an unknown channel.
 *
 * The bundle patch is the single source of truth: add a row there and this
 * script picks the new channel up automatically. When not every channel is
 * selected, the script manages <profile>/cordis.patch.yml (the part after the
 * GENERATED marker) and disables the unselected adapter rows.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';

const BUNDLE_DIR = './packages/channels';
const BUNDLE_PATCH = 'packages/channels/cordis.patch.yml';
/** Non-adapter rows that are always enabled for every channel selection. */
const INFRASTRUCTURE_ROWS = new Set([
  'channels-service',
  'channels-files',
  'channels-harness',
  'channels-control',
  'channels-web',
]);
/** Direct profile dependencies written by the pre-bundle-owned installer. */
const LEGACY_IMPLEMENTATION_PACKAGES = [
  '@wsz987/channel-core',
  '@wsz987/channel-files',
  '@wsz987/channel-harness',
  '@wsz987/channel-control',
  '@wsz987/channel-weixin',
  '@wsz987/channel-qq',
  '@wsz987/channel-dingtalk',
  '@wsz987/channel-lark',
  '@wsz987/channel-telegram',
  '@wsz987/channel-web',
];
const RUNTIME_PACKAGE_DIRS = LEGACY_IMPLEMENTATION_PACKAGES.map(
  (name) => `./packages/${name.replace('@wsz987/', '')}`,
);
/** Extra short-name aliases; the canonical names come from the bundle patch. */
const ALIASES = { wx: 'weixin', feishu: 'lark' };
const GENERATED_MARKER = '# --- generated by pnpm channels (scripts/dev-channels.mjs) ---';
const TEMPLATE = `# Your patch layer for this dsh profile, applied after every bundle layer:
# a top-level YAML array of loader patch entries (id-targeted config
# overrides, disables, and insert lists; \`!!js\` expressions allowed).
[]
`;

function fail(message) {
  console.error(`dev-channels: ${message}`);
  process.exit(1);
}

/** Minimal line-based parse of the bundle patch: `- id:` rows + their `name:`. */
function parseBundleRows() {
  if (!existsSync(BUNDLE_PATCH)) fail(`cannot find ${BUNDLE_PATCH} — run from the repo root`);
  const rows = [];
  let current = null;
  for (const raw of readFileSync(BUNDLE_PATCH, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    const idMatch = /^- id:\s*([\w-]+)/.exec(line);
    if (idMatch) {
      current = { id: idMatch[1], name: null };
      rows.push(current);
    } else if (current && !current.name) {
      const nameMatch = /^name:\s*(.+)/.exec(line);
      if (nameMatch) current.name = nameMatch[1].trim().replace(/^['"]|['"]$/g, '');
    }
  }
  if (!rows.length) fail(`no rows parsed from ${BUNDLE_PATCH}`);
  return rows;
}

/** channel short name -> patch row metadata. */
function discoverChannels(rows) {
  const channels = new Map();
  for (const row of rows) {
    if (INFRASTRUCTURE_ROWS.has(row.id)) continue;
    const short = row.id.replace(/^channels-/, '');
    channels.set(short, { id: row.id, name: row.name });
  }
  return channels;
}

function resolveProfileDir(name) {
  const home = process.env.DSH_HOME || join(homedir(), '.dsh');
  return join(home, 'profiles', name);
}

/** Normalize the user part of <profile>/cordis.patch.yml (before the marker). */
function normalizeUserSection(raw) {
  const before = raw.split(GENERATED_MARKER)[0].replace(/\s+$/, '');
  return before.replace(/\n?\[\]\s*$/, '').trimEnd();
}

function renderDisableRows(unselected) {
  return unselected.map(({ id, name }) => `- id: ${id}\n  name: '${name}'\n  disabled: true`).join('\n');
}

function writeSelectionPatch(profileDir, selection, allChannels) {
  const patchPath = join(profileDir, 'cordis.patch.yml');
  mkdirSync(dirname(patchPath), { recursive: true });
  const existing = existsSync(patchPath) ? readFileSync(patchPath, 'utf8') : TEMPLATE;
  const before = existing.split(GENERATED_MARKER)[0];
  const templateOnly = !/^\s*-\s+/m.test(before);
  const user = normalizeUserSection(existing);
  const selected = new Set(selection.map((c) => c.id));
  const unselected = [...allChannels.values()].filter((c) => !selected.has(c.id));

  let next;
  if (unselected.length === 0) {
    next = templateOnly ? TEMPLATE : user ? `${user}\n` : TEMPLATE;
  } else {
    const head = user ? `${user}\n\n` : '';
    next = `${head}${GENERATED_MARKER}\n# disabled by the local development channel selection\n${renderDisableRows(unselected)}\n`;
  }
  if (next !== existing) writeFileSync(patchPath, next);
  return unselected;
}

function checkBuilt(packages) {
  const missing = packages.filter((p) => !existsSync(join(p, 'lib')));
  if (missing.length) {
    fail(`not built: ${missing.join(', ')} — run \`pnpm build\` first (lib/ is gitignored)`);
  }
}

/** Dependencies present in the profile that are owned by this bundle. */
function managedDependencies(profileDir) {
  const manifestPath = join(profileDir, 'package.json');
  if (!existsSync(manifestPath)) return null;
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const owned = new Set(LEGACY_IMPLEMENTATION_PACKAGES);
  owned.add('@wsz987/dsh-channels');
  return Object.keys(manifest.dependencies ?? {}).filter((name) => owned.has(name));
}

function removeLegacyImplementationDependencies(profileDir) {
  const manifestPath = join(profileDir, 'package.json');
  if (!existsSync(manifestPath)) return;
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const installed = LEGACY_IMPLEMENTATION_PACKAGES.filter(
    (name) => manifest.dependencies?.[name] !== undefined,
  );
  if (installed.length === 0) return;

  console.log(`dev-channels: removing legacy direct dependencies: ${installed.join(', ')}`);
  const result = spawnSync('pnpm', ['remove', '-w', ...installed], {
    cwd: profileDir,
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });
  if (result.error) fail(`failed to run pnpm: ${result.error.message} (is pnpm on PATH?)`);
  if (result.status !== 0) fail(`pnpm remove exited with code ${result.status}`);
}

/** Strip the GENERATED marker section from cordis.patch.yml, keeping any user rows. */
function resetPatch(profileDir) {
  const patchPath = join(profileDir, 'cordis.patch.yml');
  if (!existsSync(patchPath)) return false;
  const existing = readFileSync(patchPath, 'utf8');
  const before = existing.split(GENERATED_MARKER)[0];
  const templateOnly = !/^\s*-\s+/m.test(before);
  const user = normalizeUserSection(existing);
  const next = templateOnly ? TEMPLATE : user ? `${user}\n` : TEMPLATE;
  if (next !== existing) writeFileSync(patchPath, next);
  return next !== existing;
}

/**
 * Reverse `pnpm channels`: remove the bundle through Harness plugin management,
 * clean direct implementation dependencies left by older installer versions,
 * then reset cordis.patch.yml to the user layer.
 */
function clean(profile) {
  const profileDir = resolveProfileDir(profile);
  const linked = managedDependencies(profileDir);
  const dsh = (process.env.DSH_CMD || 'npx @deepseek-ai/dsh').split(/\s+/).filter(Boolean);
  if (linked === null) {
    console.log(`dev-channels: profile ${profile} has no package.json — nothing to clean`);
  } else if (linked.length === 0) {
    console.log(`dev-channels: profile ${profile} has no dependencies managed by this bundle — nothing to remove`);
  } else {
    console.log(`dev-channels: removing from profile ${profile}: ${linked.join(', ')}`);
    const bundleName = '@wsz987/dsh-channels';
    const hasBundle = linked.includes(bundleName);
    if (hasBundle) {
      const result = spawnSync(dsh[0], [...dsh.slice(1), 'plugin', '--profile', profile, 'remove', bundleName], {
        stdio: 'inherit',
        shell: process.platform === 'win32',
      });
      if (result.error) fail(`failed to run ${dsh.join(' ')}: ${result.error.message} (is npx/pnpm on PATH?)`);
      if (result.status !== 0) fail(`dsh plugin exited with code ${result.status}`);
    }
    const implementations = linked.filter((name) => name !== bundleName);
    if (implementations.length > 0) {
      const result = spawnSync('pnpm', ['remove', '-w', ...implementations], {
        cwd: profileDir,
        stdio: 'inherit',
        shell: process.platform === 'win32',
      });
      if (result.error) fail(`failed to run pnpm: ${result.error.message} (is pnpm on PATH?)`);
      if (result.status !== 0) fail(`pnpm remove exited with code ${result.status}`);
    }
  }
  const patched = resetPatch(profileDir);
  if (patched) console.log(`dev-channels: reset ${join(profileDir, 'cordis.patch.yml')} to the user layer`);
  console.log(`dev-channels: cleaned ${profile} — reinstall with \`${dsh.join(' ')} plugin --profile ${profile} add -w @wsz987/dsh-channels@latest\``);
}

function run(args) {
  const help = () => {
    const channels = discoverChannels(parseBundleRows());
    const names = [...channels.keys()].sort();
    console.log(`dev-channels — install the @wsz987/dsh-channels bundle from this workspace into a dsh profile

usage: pnpm channels [options] [channel...]

  --profile <name>   target profile (default: web)
  --all              install every channel (default when no channel is given)
  --clean            remove this bundle's managed packages from the profile
  -h, --help         this help

channels (from ${BUNDLE_PATCH}):
  ${names.join(', ')}

aliases: ${Object.entries(ALIASES).map(([k, v]) => `${k} -> ${v}`).join(', ')}
`);
  };

  let profile = 'web';
  let all = false;
  let cleanMode = false;
  const positionals = [];
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a === '-h' || a === '--help') return help(), process.exit(0);
    if (a === '--profile') profile = args[++i] ?? fail('--profile needs a name');
    else if (a === '--all') all = true;
    else if (a === '--clean') cleanMode = true;
    else if (a.startsWith('-')) fail(`unknown option ${a}`);
    else positionals.push(a);
  }

  if (cleanMode) return clean(profile);

  const bundle = parseBundleRows();
  const channels = discoverChannels(bundle);
  let selection;
  if (positionals.length === 0 || all) {
    selection = [...channels.values()];
  } else {
    const picked = [];
    for (const raw of positionals) {
      const short = ALIASES[raw] ?? raw;
      const ch = channels.get(short);
      if (!ch) {
        console.error(`dev-channels: unknown channel '${raw}' — available: ${[...channels.keys()].sort().join(', ')}`);
        process.exit(1);
      }
      picked.push(ch);
    }
    selection = picked;
  }

  const sourcePackages = [BUNDLE_DIR, ...RUNTIME_PACKAGE_DIRS];
  const missingDir = sourcePackages.filter((p) => !existsSync(p));
  if (missingDir.length) fail(`workspace dirs not found: ${missingDir.join(', ')}`);
  checkBuilt(sourcePackages);

  console.log(`dev-channels: profile=${profile} channels=${selection.map((c) => c.id).join(',') || '(none)'}`);
  const dsh = (process.env.DSH_CMD || 'npx @deepseek-ai/dsh').split(/\s+/).filter(Boolean);
  // The profile owns one direct dependency. Every loader entry is exported by
  // the bundle itself, matching the registry install and Harness bundle model.
  const bundleResult = spawnSync(dsh[0], [...dsh.slice(1), 'plugin', '--profile', profile, 'add', '-w', BUNDLE_DIR], {
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });
  if (bundleResult.error) fail(`failed to run ${dsh.join(' ')}: ${bundleResult.error.message} (is npx/pnpm on PATH?)`);
  if (bundleResult.status !== 0) fail(`dsh plugin exited with code ${bundleResult.status}`);

  const profileDir = resolveProfileDir(profile);
  removeLegacyImplementationDependencies(profileDir);

  const unselected = writeSelectionPatch(profileDir, selection, channels);
  if (unselected.length) {
    console.log(`dev-channels: disabled ${unselected.length} row(s) in ${join(resolveProfileDir(profile), 'cordis.patch.yml')}: ${unselected.map((c) => c.id).join(', ')}`);
    console.log('dev-channels: re-run with the missing channels (or no args = all) to re-enable them');
  } else {
    console.log('dev-channels: all channels enabled');
  }
  console.log(`dev-channels: done — boot with \`${dsh.join(' ')} ${profile === 'web' ? 'web' : `--profile ${profile}`}\``);
}

run(process.argv.slice(2));
